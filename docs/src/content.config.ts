import { defineCollection, z } from 'astro:content';
import { file } from 'astro/loaders';
import { docsLoader } from '@astrojs/starlight/loaders';
import { docsSchema } from '@astrojs/starlight/schema';

const example = z.object({
    title: z.string().nullable(),
    code: z.string(),
});

const verdict = z.object({
    verdict: z.enum(['ok', 'fail', 'lossy']),
    note: z.number().optional(),
});

export const collections = {
    docs: defineCollection({ loader: docsLoader(), schema: docsSchema() }),

    // AST node classes of type-lang/types, written by bin/build-ast.php.
    ast: defineCollection({
        loader: file('src/data/toolkit/ast.json'),
        schema: z.object({
            name: z.string(),
            group: z.string(),
            kind: z.enum(['final', 'abstract', 'enum', 'interface']),
            parent: z.string().nullable(),
            description: z.string(),
            properties: z.array(z.object({
                name: z.string(),
                type: z.string(),
                isReadonly: z.boolean(),
                description: z.string(),
            })),
            cases: z.array(z.object({ name: z.string(), description: z.string() })),
        }),
    }),

    // Syntax comparison of the parsers, one entry per section of the page.
    comparison: defineCollection({
        loader: file('src/data/language/comparison.json'),
        schema: z.object({
            title: z.string(),
            isMalformed: z.boolean(),
            cases: z.array(z.object({
                type: z.string(),
                verdicts: z.object({ phpstan: verdict, psalm: verdict, typelang: verdict }),
            })),
            notes: z.record(z.string(), z.string()),
        }),
    }),

    // Generated by bin/build-tags.php from the model of type-lang/phpdoc.
    phpdocTags: defineCollection({
        loader: file('src/data/phpdoc/tags.json'),
        schema: z.object({
            tag: z.string(),
            class: z.string(),
            alias: z.object({ isRuntime: z.boolean() }).nullable(),
            summary: z.string(),
            since: z.string().nullable(),
            deprecated: z.string().nullable(),
            registrations: z.record(z.string(), z.array(z.string())),
            grammar: z.array(z.string()).min(1),
            examples: z.array(example),
            canonicalExamples: z.array(example).nullable(),
        }),
    }),
};
